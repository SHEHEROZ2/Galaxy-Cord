export function generateDockerfile(port = 8080): string {
  return `# NexusCord Standalone Server Dockerfile
FROM node:20-alpine

WORKDIR /app

COPY package.json ./
RUN npm install --production

COPY nexus-server.mjs ./

ENV PORT=${port}
ENV HOST=0.0.0.0
EXPOSE ${port}

CMD ["node", "nexus-server.mjs"]
`;
}

